// ============================================================================
// demo 09 —— 预处理器：宏替换与条件编译
// ============================================================================
// 理论：预处理是【纯文本阶段】，发生在词法分析之前 —— 它不认识类型、
//   不认识作用域，只认 Token 与宏定义。这也是它一切"反直觉"的来源：
//   宏是文本替换，不是函数调用。
//
//   一个典型的坑：`#define SQUARE(x) ((x)*(x))` 里的括号【必须】写足 ——
//   写成 `x*x` 的话，`SQUARE(1+2)` 会展开成 `1+2*1+2` = 5 而不是 9。
//
// 看预处理日志：
//   ./build-linux/minicc demos/core/02_preprocessor.cpp -S -o /tmp/demo09.s
//   grep "\[pp\]" /tmp/demo09.log | head -30
//   可见每个宏调用点的展开记录，以及条件编译分支的取舍。
//
// 也可以只跑预处理（-E），直接看展开后的文本：
//   ./build-linux/minicc demos/core/02_preprocessor.cpp -E
//
// 预期：退出码 0
// ============================================================================

#define MAX 100
#define SQUARE(x) ((x) * (x))     // ★ 括号写足，否则 SQUARE(1+2) ≠ 9

int main() {
    // ① 对象宏：直接文本替换
    int m = MAX;
    if (m != 100) return 1;

    // ② 函数宏：参数按文本代入，括号保证优先级
    int sq = SQUARE(3);
    if (sq != 9) return 2;

    // ③ 条件编译：被裁掉的分支根本不会进入词法分析
#if MAX > 50
    int which = 1;
#else
    int which = 0;
#endif
    if (which != 1) return 3;

    return 0;
}
