// ============================================================================
// demo 07 —— 别名模板与 CTAD：两条"少写几个字"的路
// ============================================================================
// 理论一：别名模板（[temp.alias]）
//     template <class T> using P = MyPtr<T>;
//   ★ 别名【不是新类型】—— `P<int>` 与 `MyPtr<int>` 是同一个类型，不会多出
//     类、也不会多发符号。它只是"解糖"，所以没有"实例化"这回事。
//
// 理论二：类模板实参推导 CTAD（[dcl.type.class.deduct]）
//     MyPtr m(&v);      // 没写 <int>，由构造函数形参反推 T
//   ★ CTAD【只在直接初始化触发】—— 必须写成 `MyPtr m(&v);`，
//     写成 `MyPtr m = &v;` 是不触发的（那是拷贝初始化）。
//   实现上它与函数模板推导是【同一套合一算法的反向使用】：
//     模式来自构造函数形参表，实参来自调用处。
//
// 看解糖与推导：
//   ./build-linux/minicc demos/tmpl/07_alias_and_ctad.cpp -S -o /tmp/demo07.s
// 预期：退出码 0
//
// ⚠ 已知边界（写这个 demo 时发现，尚未修）：
//   方法体内的【裸字段名赋值】`ptr = x;` 走的是 emitAssign 的 Var 分支，
//   那条路径硬编码 `movl`（4 字节写入）。给 8 字节指针字段赋值时高 32 位被截断，
//   症状是构造完 `m.ptr != &v`。
//   本项目一共【三条】字段写路径：初始化列表、成员表达式 `q.p = v`、
//   方法体内裸字段名 `ptr = x;`。前两条已按字段宽度分派，第三条漏了。
//   故本 demo 的构造函数改用初始化列表。
// ============================================================================

template <class T>
class MyPtr {
public:
    T* ptr;

    // 用初始化列表而非 `ptr = x;` —— 后者走"方法体内裸字段名赋值"路径，
    // 那条路径目前硬编码 4 字节写入（已知边界，见文件尾注）。
    MyPtr(T* x) : ptr(x) {}
};

// 别名模板：不是新类型，只是给 MyPtr<T> 起个短名
template <class T>
using P = MyPtr<T>;

int main() {
    int v = 7;

    // ① CTAD：由构造实参 &v（int*）反推出 T = int
    MyPtr m(&v);
    if (m.ptr != &v) return 1;

    // ② 显式写实参 —— 老路径，不走 CTAD
    MyPtr<int> n(&v);
    if (n.ptr != &v) return 2;

    // ③ 别名模板解糖成 MyPtr<int>：两者是同一个类型
    P<int> q(&v);
    if (q.ptr != &v) return 3;

    return 0;
}
