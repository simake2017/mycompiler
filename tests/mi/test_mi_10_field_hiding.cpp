// =============================================================================
// 测试：派生类同名字段【隐藏】基类字段（[class.member.lookup]/3）
// =============================================================================
// 理论点：
//   - 派生类声明的成员声明会【隐藏】基类里的同名声明：`d.x` 找的是 D::x，
//     基类那份要靠限定名 `d.A::x` 才拿得到。
//   - 与"歧义"（[class.member.lookup]/8，两个不同基类子对象各有一份）是两回事：
//     隐藏是合法且唯一的，歧义是 ill-formed。
// 预期行为：
//   - 布局：A.x@0、D.x@8（两份都在，各占一格）
//   - `d.x` 命中 D::x；`d.getA()` 读到的仍是 A::x
//   - 运行返回 7*10 + 5 = 75
// 回归背景（docs/BUGS.md B14）：
//   - 修复前"自身字段与基类字段撞名 ⇒ 把自身改名为 'D.x'"，而查找第二步是按
//     `sourceClass + "." + name` 反拼前缀 —— 于是裸名 x 精确配上了 ['A' 的 x]，
//     隐藏方向反了：d.x 静默指向 A::x（返回 77 而非 75）。
//   - 根因是把【显示名】当成了【查找键】：名字是可读标签，不是索引。
//     clang 的成员查找走 LookupResult（候选带"来自哪个子对象"），从不拼字符串。
// =============================================================================

class A {
public:
    int x;
    void setA(int v) { x = v; }   // 经基类方法写 A::x（方法体内 x 解析为 A 自己的）
    int  getA() { return x; }
};

class D : public A {
public:
    int x;                 // 隐藏 A::x（合法，非歧义）
};

int main() {
    D d;
    d.setA(7);                    // A::x = 7（偏移 0）
    d.x = 5;                      // ★ 应写 D::x（偏移 8）
    return d.getA() * 10 + d.x;   // clang = 75；修复前 d.x 落到 A::x ⇒ 55
}
