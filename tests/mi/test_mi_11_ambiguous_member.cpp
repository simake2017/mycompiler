// =============================================================================
// 测试：两个基类子对象各有一个同名字段 ⇒ 歧义必须报错（[class.member.lookup]/8）
// =============================================================================
// 理论点：
//   - 名字查找在多个【不同基类子对象】里都找到同名成员 ⇒ ill-formed，
//     必须用限定名消歧（`d.B::name`）。minicc 尚无限定成员访问，故只能拒绝。
//   - 与"隐藏"（/3，派生类声明隐藏基类声明）方向相反：那是合法且唯一的。
// 预期行为（两条场景，都必须是【响亮报错】而非静默取一个）：
//   场景 1 两个非多态基类各有一个 name
//   场景 2 祖辈链带来的名字与直接基类撞名（X : P, B，而 P 自己也继承 B）
// 期望报错文案（含歧义候选的来源子对象）：
//   [ERROR] [Semantic Error] 5:20: Member 'name' is ambiguous in class 'D':
//     found in 2 base-class subobjects (经 'A' 的 'A.name'、经 'A' 的 'A.name')
// 回归背景（docs/BUGS.md B13/B15）：
//   - 修复前：布局里两条记录被压成同名（"A.name" 与 "A.name"），第二条的偏移被
//     算成 0；查找"先到先得"静默绑第一个 ⇒ 静默接受非法程序 + 布局打印错。
//   - 修复后：偏移按 (viaBase, baseFieldIndex) 精确算，查找报歧义。
//
// ⚠ 本文件【预期编译失败】(rc=1)，由 logdiff 基线固化其退出码与报错原文；
//   若某天 rc 变成 0，说明歧义检测退化了 —— 那正是这条回归要抓的。
// =============================================================================

class B {
public:
    int name;
};

class C {
public:
    int name;
};

class A : public B, public C {
};

class D : public A {
public:
    int tag;
};

int main() {
    D d;
    d.name = 1;     // ← 歧义点：B::name 与 C::name 分属两个子对象
    return d.tag;
}
