// =============================================================================
// 测试：虚函数槽的身份不是"裸名"（BUGS.md B20 缺陷 c）
// =============================================================================
// 理论点：
//   - vtable 槽位的身份是什么？clang 的答案是 **GlobalDecl 句柄**（Decl* + 种类），
//     槽位匹配就是比较两个句柄。minicc 的 vtable 条目里只有**字符串**（`.quad <sym>`），
//     字符串是给人看的、不是给机器比的 ⇒ 一旦"身份"窄化成裸名，就会认错人。
//   - 具体现场：`virtual int f();  int f(int);` —— 两条声明**裸名相同**。
//     旧实现按裸名匹配槽位 ⇒ 非虚的 `f(int)` 认领了虚的 `f()` 的槽位，
//     并且被顺手标上 virtual。汇编层看不见任何异常（没有报错、没有非法符号），
//     症状是**运行结果错**：`c.f(2)` 走虚调用、跳进 `f()` ⇒ 返回 255（B20 c 原文）。
//   - 修法：槽位身份 = **裸名 + 形参类型链**（VTableEntry::signature）。
//     这与"成员方法身份 = 名字 + 形参类型"（B22）是**同一条判据**——两处必须同源。
//   - 对照 clang：[class.virtual]/2 的覆写判据是（名字 + 形参类型列表 + cv 限定），
//     裸名只是查找的入口，不是身份的全体。
// 预期行为：
//   - 基类 `virtual int f()` 与非虚 `int f(int)` 并存，各调各的（1 / 12）
//   - 派生类覆写 `f()`，槽位只有**一个**虚槽（`f(int)` 不得占槽）
//   - 通过基类指针调 `f()` 走覆写后的实现
//   - 运行返回 0
// ★ 边界（本轮**未做**，另行记录）：`Derived::f()` 一旦声明，基类的 `f(int)` 整族
//   按 [class.member.lookup]/3 被**隐藏**，`d.f(2)` 在 clang 下是错误
//   （"too many arguments to function call; did you mean 'Base::f'"）。
//   minicc 的 findMethodInHierarchy 是"本地找不到才往基类走" ⇒ 按**裸名**判在不在，
//   于是把被隐藏的 `Base::f(int)` 也捞了出来 —— 又一处"身份比裸名宽"。
//   本用例因此只经 `Base b` 调 `f(int)`，保证 clang/minicc 双侧合法。
// =============================================================================

class Base {
public:
    virtual int f() { return 1; }
    int f(int x) { return x + 10; }     // 同名、不同个数 —— 不是覆写，不该占虚槽
};

class Derived : public Base {
public:
    virtual int f() { return 100; }     // 覆写 Base::f()
};

int main() {
    Base b;
    if (b.f() != 1) return 1;
    if (b.f(2) != 12) return 2;         // 旧实现：走虚调用跳进 f() ⇒ 255

    Derived d;
    if (d.f() != 100) return 3;         // 本地覆写，直接调用

    Base* p = &d;
    if (p->f() != 100) return 4;        // 虚调用走覆写（槽位身份若是裸名，这里会跳错）

    return 0;
}
