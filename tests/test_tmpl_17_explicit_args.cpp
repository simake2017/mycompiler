// =============================================================================
// test_tmpl_17_explicit_args.cpp —— S3 正例：显式实参（全显式 + 部分显式）
// =============================================================================
// 考察理论点：显式实参占模板参数表前缀（[temp.explicit] 与 [temp.deduct]），
//   剩余参数继续从调用实参推导 —— "显式给定 / 推导补全"的混合模式。
//   另考察 Parser 的 template-id 歧义消解：mix<int>(...) 中的 <int>
//   必须被识别为模板实参而非比较表达式（判据：其后紧跟 '('）。
//
// 预期行为：
//   mix<int>(1, 2)     → T := int（显式），U := int（推导）→ 返回 1
//   mix<int, int>(3,4) → 全显式 → 返回 3
//   退出码 = 0（1 + 3 - 4）
// =============================================================================

template<typename T, typename U>
T mix(T a, U b) {
    return a;
}

int main() {
    int r1 = mix<int>(1, 2);
    int r2 = mix<int, int>(3, 4);
    return r1 + r2 - 4;
}
