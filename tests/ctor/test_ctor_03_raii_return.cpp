// =============================================================================
// 测试：return 路径上的 RAII 析构（Destruction on Early Return）
// =============================================================================
// 理论点：
//   - 局部对象的析构时机是【离开作用域】，而不是"函数末尾"这个位置
//     （[class.dtor]/2、[basic.stc]）—— return 是提前出口，析构必须在那里补上。
//   - 析构顺序 LIFO：后构造的先析构，且【跨作用域层】由内向外
//     （[class.dtor]/2 + [basic.stc.dcl]）。
// 预期行为：
//   - 修复前（BUGS.md B4）：析构发在 leave; ret 【之后】⇒ 死代码，g 恒为 0。
//   - 修复后：main 返回 121。推导：
//       f() 析构 a(id=1)          ⇒ g = 0*10+1 = 1
//       h() 先析构 b(id=2) 再 a(1) ⇒ g = 1*10+2 = 12 → 12*10+1 = 121
//     （只析构最外层 / 顺序反了 / 漏了内层，都会得到别的数：1 / 11 / 12 / 21 …，
//       所以这一个返回值同时钉住了"跨层"与"LIFO"两件事）
//   - 对照 clang++-18：同样返回 121。
// =============================================================================

int g = 0;

class Tracer {
public:
    int id;

    Tracer(int i) : id(i) {}

    ~Tracer() { g = g * 10 + id; }
};

// 场景①：函数级对象 + return —— 析构曾整段不可达
int f() {
    Tracer a(1);
    return 0;
}

// 场景②：嵌套块内的 return —— 析构必须跨两层、由内向外
int h() {
    Tracer a(1);
    {
        Tracer b(2);
        return 0;
    }
    return 0;
}

int main() {
    f();
    h();
    return g;
}
