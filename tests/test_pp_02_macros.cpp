// =============================================================================
// test_pp_02_macros.cpp —— P0 正例：对象宏 + 函数宏 + 嵌套展开 + #undef
// =============================================================================
// 考察理论点（[cpp.replace] / [cpp.subst] / [cpp.rescan]）：
//   1. 函数宏：实参先展开 → 按词边界替换参数名 → 整体重扫描
//   2. 嵌套：宏实参本身是宏名（compose(twice, 20)），替换后重扫描触发二次展开
//   3. 自引用"涂蓝"：展开体中的同名宏不再展开（本例未触发死循环即证明）
//   4. #undef 后宏消失
//
// 预期行为：Phase 0 逐条打印 define/expand；退出码 = 0
// =============================================================================

#define ANSWER 42
#define twice(x) ((x) + (x))
#define add(a, b) ((a) + (b))
#define compose(f, v) f(v)

int main() {
    int v = twice(20);            // 40
    int w = add(1, ANSWER);       // 43（实参 ANSWER 先展开为 42）
    int c = compose(twice, 20);   // 40（宏作实参 + 重扫描）
#undef ANSWER
    return v + w + c - 123;       // 40 + 43 + 40 - 123 = 0
}
