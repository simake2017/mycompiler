// =============================================================================
// 测试：decltype 基础（[dcl.type.decltype]）
// =============================================================================
// 考察理论点：
//   decltype 是"表达式 → 类型"的查询算子：给一个表达式，问它的类型是什么。
//   它在【编译期】完成，运行期不留任何痕迹（不产生符号、不产生指令）。
//
//   两种求值时机（本测试覆盖前者）：
//     ① 非依赖上下文：操作数里没有模板参数，语义分析时立刻求出结果
//     ② 依赖上下文  ：操作数含模板参数，必须延迟到替换阶段
//        —— 见 test_tmpl_35 的 void_t<decltype(...)> 探测
//
//   三个使用形态：
//     decltype(变量)       → 变量的声明类型
//     decltype(函数调用)   → 函数返回类型
//     decltype(&变量)      → 指针类型（取地址 [expr.unary.op]/3）
//
// 预期行为：全部类型推导正确、编译通过、返回 0。
//
// 编译过程中的关键日志：
//   [parse:type] base = decltype(e) [deferred: 不求值，留待替换阶段]
//   [decltype] resolveType 遇到 decltype 节点，尝试立即求值
//   [decltype]   ⇒ 声明类型 = int
//   [infer] &a → int*    (取地址 [expr.unary.op]/3)
//
// 对照 clang：clang++-18 -std=c++20 编译本文件，退出码一致。
// =============================================================================

int twice(int x) { return x + x; }

int main() {
    int a = 7;

    // ① decltype(变量) → 变量的声明类型
    decltype(a) b = 3;          // b : int
    b = b + 1;                  // 4

    // ② decltype(函数调用) → 函数返回类型
    decltype(twice(1)) c = 5;   // c : int
    c = c + 1;                  // 6

    // ③ decltype(&变量) → 指针类型
    decltype(&a) p = &a;        // p : int*
    // 通过指针读回，验证 & 真的取到了 a 的地址（而不是 a 的值）
    // 若实现错误地取了值，这里会得到垃圾值

    if (b != 4) return 91;
    if (c != 6) return 92;

    // 累加：4 + 6 = 10
    return b + c - 10;
}
