// =============================================================================
// test_tmpl_16_conflict_error.cpp —— S2 错误用例：同一 T 的冲突绑定
// =============================================================================
// 考察理论点：替换合成的一致性 —— 合一算法要求同一变量的两次绑定相等。
//   mix2(1, true)：第一对 T := int，第二对 T := bool → 冲突。
//
// 期望报错（退出码 1）：
//   conflicting types for deduction of 'T': previously deduced 'int', now 'bool'
// =============================================================================

template<typename T>
T mix2(T a, T b) {
    return a;
}

int main() {
    return mix2(1, true);
}
