// =============================================================================
// 测试：偏序裁决与【声明顺序】无关
// =============================================================================
// 考察理论点：
//   本测试的模板与 test_tmpl_40 【完全等价】，唯一改动是把两条偏特化的
//   【声明顺序颠倒】过来：
//
//     test_tmpl_40:  Box<T*>  先， Box<T**> 后
//     本测试:        Box<T**> 先， Box<T*>  后
//
//   两者必须得到【一模一样】的结果。这是偏序裁决区别于
//   "先注册者胜 / 后注册者胜"这类偷懒实现的判别性实验：
//
//     若实现是"取第一个匹配的偏特化" → 本测试会退化成选 T**（碰巧对），
//                                      而 40 会错选 T*
//     若实现是"取最后一个"           → 40 对，本测试错
//     只有真正做偏序                   → 两个都对
//
//   ★ 这条测试的意义在于：它把"实现碰巧对了"和"实现真的对了"区分开。
//     只写 40 的话，一个"取最后一个匹配者"的错误实现也能全绿 ——
//     因为 40 里更特化的 T** 恰好声明在后面。加上 41 才形成闭环。
//     （同类手法见 docs/learn/19 里对"先注册者胜"的证伪实验。）
//
//   标准依据：[temp.class.order] 规定择优是【模式之间的关系】，
//   与声明位置的先后没有任何关系。对照 clang：
//   Sema::isMoreSpecializedThan 只看模式，不看声明顺序。
//
// 预期行为：与 test_tmpl_40 完全一致 —— 0 / 1 / 2，返回 0。
//
// 编译过程中的关键日志：
//   注册顺序变了，但 [order] 裁决结论不变：
//   [order] ✓ 'Box<T**>' 比 'Box<T*>' 更特化
//
// 对照 clang：clang++-18 -std=c++20 编译本文件，退出码一致
//            （且与 test_tmpl_40 的退出码相同）。
// =============================================================================

template <typename T>
struct Box {
    int tag() { return 0; }   // 主模板
};

// ★ 注意：更特化的 T** 这次【先】声明
template <typename T>
struct Box<T**> {
    int tag() { return 2; }
};

// ★ 较一般的 T* 这次【后】声明
template <typename T>
struct Box<T*> {
    int tag() { return 1; }
};

int main() {
    Box<int>   a;
    Box<int*>  b;
    Box<int**> c;

    // 结论必须与 test_tmpl_40 逐字相同
    if (a.tag() != 0) return 90;
    if (b.tag() != 1) return 91;   // 若实现"取最后一个"→ 这里会得到 2（因为 T** 在前）
    if (c.tag() != 2) return 92;   // 若实现"取第一个"  → 这里会得到 2 但 b 错

    return 0;
}
