// =============================================================================
// 测试：三路偏序 —— 链式更特化关系的传递裁决
// =============================================================================
// 考察理论点：
//   偏序裁决不能只处理"两个候选"的情形。真实代码里可能有 N 个偏特化
//   同时匹配，需要从中挑出【唯一最特化的那一个】。
//
//   本测试布下一条完全链：
//     Box<T>   ⊂  Box<T*>  ⊂  Box<T**>  ⊂  Box<T***>
//     （左端最一般，右端最特化；⊂ 读作"被包含于"）
//
//   观察点在于"同时匹配的候选数"随实参变化：
//     Box<int>      → 0 个偏特化匹配          → 主模板        (0)
//     Box<int*>     → 1 个匹配（T*）          → 无需裁决      (1)
//     Box<int**>    → 2 个匹配（T*, T**）     → 二路裁决      (2)
//     Box<int***>   → 3 个匹配（T*, T**, T***）→ 三路裁决     (3)
//
//   ★ 三路裁决的实现要点：不能简单地"两两比一遍取第一个赢家"就收工。
//     正确做法是把每个候选 i 与所有其他候选 j 逐一比较，
//     只有当【没有任何 j 比 i 更特化】时，i 才是最终赢家（无冕之王）。
//     本项目 selectClassTemplate 的 dominance 循环即按此写：
//        赢家 i ⟺ ∀ j≠i: ¬(j 比 i 更特化)
//     若找不出这样的 i（即 test_tmpl_42 的歧义情形）→ 报错。
//
//   ★ 三路也顺带验证了偏序的【传递性】：
//     T*** > T** 且 T** > T*  ⇒ T*** 必然 > T*，
//     即使实现里 T* 与 T*** 可能从未被直接比过，
//     靠传递性 + dominance 循环依然能得到正确答案。
//
// 预期行为：0 / 1 / 2 / 3 各就各位，返回 0。
//
// 编译过程中的关键日志：
//   [spec:select] ★ 3 个偏特化候选同时匹配 —— 进入 [temp.class.order] 偏序裁决
//   [order] 'Box<T***>' 胜过 'Box<T**>'；'Box<T**>' 胜过 'Box<T*>'
//   [order] ✔ 唯一最特化候选：'Box<T***>'
//
// 对照 clang：clang++-18 -std=c++20 编译本文件，退出码一致。
// =============================================================================

template <typename T>
struct Box {
    int tag() { return 0; }   // 主模板
};

template <typename T>
struct Box<T*> {
    int tag() { return 1; }
};

template <typename T>
struct Box<T**> {
    int tag() { return 2; }
};

template <typename T>
struct Box<T***> {
    int tag() { return 3; }
};

int main() {
    Box<int>    a;   // 无偏特化匹配
    Box<int*>   b;   // 1 个匹配
    Box<int**>  c;   // 2 个匹配 → 二路裁决
    Box<int***> d;   // 3 个匹配 → 三路裁决

    if (a.tag() != 0) return 90;
    if (b.tag() != 1) return 91;
    if (c.tag() != 2) return 92;
    if (d.tag() != 3) return 93;

    return 0;
}
